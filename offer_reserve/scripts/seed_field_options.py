async def main() -> None:
    bt = BitableClient()
    table = bt.table("field_options")
    existing = await bt.list_records(table)
    existing_names = {r["fields"].get("细分方向") for r in existing}
    payload = [
        {
            **seed,
            "启用": True,
        }
        for seed in SEEDS
        if seed["细分方向"] not in existing_names
    ]
    if not payload:
        print("✅ 所有方向已存在，无需重复写入")
        return
    created = await bt.batch_create(table, payload)
    print(f"✅ 写入 {len(created)} 个方向")


if __name__ == "__main__":
    asyncio.run(main())
